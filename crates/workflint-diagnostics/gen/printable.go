//go:build ignore

// printable.go writes src/quote/printable.rs: the code point ranges that Go's
// strconv.IsPrint accepts. Run it from the crate directory:
//
//	go run gen/printable.go > src/quote/printable.rs
package main

import (
	"fmt"
	"runtime"
	"strconv"
	"unicode"
)

func main() {
	type span struct{ lo, hi rune }
	var spans []span
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !strconv.IsPrint(r) {
			continue
		}
		if n := len(spans); n > 0 && spans[n-1].hi == r-1 {
			spans[n-1].hi = r
		} else {
			spans = append(spans, span{r, r})
		}
	}

	fmt.Printf("// Generated by `go run gen/printable.go` with %s (Unicode %s). Do not edit.\n\n", runtime.Version(), unicode.Version)
	fmt.Println("/// Inclusive code point ranges that Go's `strconv.IsPrint` accepts, in ascending order.")
	fmt.Printf("pub(super) static PRINTABLE: [(u32, u32); %d] = [\n", len(spans))
	for _, s := range spans {
		fmt.Printf("    (0x%04x, 0x%04x),\n", s.lo, s.hi)
	}
	fmt.Println("];")
}
